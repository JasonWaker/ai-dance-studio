create table if not exists public.under3_low_odds_matches (
  id bigint generated by default as identity primary key,
  match_key text not null unique,
  scan_batch_id text,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  kickoff_at timestamptz not null,
  competition_name text not null,
  competition_country text,
  competition_level text,
  home_team text not null,
  away_team text not null,
  source_match_id text,
  trigger_main_ou_line numeric(4,2),
  trigger_main_over_odds numeric(6,3),
  trigger_main_under_odds numeric(6,3),
  trigger_under3_odds numeric(6,3) not null check (trigger_under3_odds between 1.62 and 1.69),
  trigger_over3_odds numeric(6,3),
  latest_main_ou_line numeric(4,2),
  latest_main_over_odds numeric(6,3),
  latest_main_under_odds numeric(6,3),
  latest_under3_odds numeric(6,3),
  latest_over3_odds numeric(6,3),
  is_165_focus boolean generated always as (trigger_under3_odds between 1.64 and 1.66) stored,
  odds_source text,
  source_url text,
  signal_rule text not null default 'under3_odds_1.62_1.69_goal3plus',
  status text not null default 'scheduled' check (status in ('scheduled','live','settled','cancelled','postponed')),
  home_score smallint check (home_score is null or home_score >= 0),
  away_score smallint check (away_score is null or away_score >= 0),
  total_goals smallint generated always as (
    case when home_score is not null and away_score is not null then home_score + away_score else null end
  ) stored,
  goals_3plus_hit boolean generated always as (
    case when home_score is not null and away_score is not null then (home_score + away_score) >= 3 else null end
  ) stored,
  settled_at timestamptz,
  result_source text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.under3_low_odds_snapshots (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.under3_low_odds_matches(id) on delete cascade,
  captured_at timestamptz not null default now(),
  main_ou_line numeric(4,2),
  main_over_odds numeric(6,3),
  main_under_odds numeric(6,3),
  under3_odds numeric(6,3) check (under3_odds is null or under3_odds > 1),
  over3_odds numeric(6,3) check (over3_odds is null or over3_odds > 1),
  odds_source text,
  source_url text
);

create index if not exists under3_low_odds_matches_kickoff_idx on public.under3_low_odds_matches(kickoff_at);
create index if not exists under3_low_odds_matches_status_idx on public.under3_low_odds_matches(status);
create index if not exists under3_low_odds_matches_trigger_odds_idx on public.under3_low_odds_matches(trigger_under3_odds);
create index if not exists under3_low_odds_matches_main_line_idx on public.under3_low_odds_matches(trigger_main_ou_line);
create index if not exists under3_low_odds_snapshots_match_time_idx on public.under3_low_odds_snapshots(match_id, captured_at desc);

alter table public.under3_low_odds_matches enable row level security;
alter table public.under3_low_odds_snapshots enable row level security;

drop policy if exists under3_low_odds_matches_public_read on public.under3_low_odds_matches;
create policy under3_low_odds_matches_public_read
on public.under3_low_odds_matches for select
to anon, authenticated
using (true);

drop policy if exists under3_low_odds_snapshots_public_read on public.under3_low_odds_snapshots;
create policy under3_low_odds_snapshots_public_read
on public.under3_low_odds_snapshots for select
to anon, authenticated
using (true);

grant select on public.under3_low_odds_matches to anon, authenticated;
grant select on public.under3_low_odds_snapshots to anon, authenticated;

create or replace view public.under3_low_odds_dashboard
with (security_invoker = true) as
select
  m.*,
  timezone('Asia/Shanghai', m.kickoff_at) as kickoff_beijing,
  case when m.goals_3plus_hit is true then '>=3球' when m.goals_3plus_hit is false then '<=2球' else '待结算' end as result_label,
  case when m.is_165_focus then '1.65重点样本' else '普通样本' end as focus_label,
  (select count(*)::bigint from public.under3_low_odds_snapshots s where s.match_id = m.id) as snapshot_count
from public.under3_low_odds_matches m;

grant select on public.under3_low_odds_dashboard to anon, authenticated;

create or replace view public.under3_low_odds_stats
with (security_invoker = true) as
select
  count(*)::bigint as total_samples,
  count(*) filter (where status = 'scheduled')::bigint as scheduled_samples,
  count(*) filter (where status = 'settled')::bigint as settled_samples,
  count(*) filter (where status = 'settled' and goals_3plus_hit is true)::bigint as goals_3plus_count,
  count(*) filter (where status = 'settled' and goals_3plus_hit is false)::bigint as goals_le2_count,
  round(100.0 * count(*) filter (where status = 'settled' and goals_3plus_hit is true) / nullif(count(*) filter (where status = 'settled'), 0), 2) as goals_3plus_rate,
  count(*) filter (where is_165_focus)::bigint as focus_165_samples,
  count(*) filter (where is_165_focus and status = 'settled')::bigint as focus_165_settled,
  count(*) filter (where is_165_focus and status = 'settled' and goals_3plus_hit is true)::bigint as focus_165_goals_3plus,
  round(100.0 * count(*) filter (where is_165_focus and status = 'settled' and goals_3plus_hit is true) / nullif(count(*) filter (where is_165_focus and status = 'settled'), 0), 2) as focus_165_goals_3plus_rate
from public.under3_low_odds_matches;

grant select on public.under3_low_odds_stats to anon, authenticated;

create or replace view public.under3_low_odds_stats_by_odds
with (security_invoker = true) as
select
  trigger_under3_odds,
  count(*)::bigint as samples,
  count(*) filter (where status = 'settled')::bigint as settled,
  count(*) filter (where status = 'settled' and goals_3plus_hit is true)::bigint as goals_3plus,
  round(100.0 * count(*) filter (where status = 'settled' and goals_3plus_hit is true) / nullif(count(*) filter (where status = 'settled'), 0), 2) as goals_3plus_rate
from public.under3_low_odds_matches
group by trigger_under3_odds
order by trigger_under3_odds;

grant select on public.under3_low_odds_stats_by_odds to anon, authenticated;

create or replace view public.under3_low_odds_stats_by_main_line
with (security_invoker = true) as
select
  trigger_main_ou_line,
  count(*)::bigint as samples,
  count(*) filter (where status = 'settled')::bigint as settled,
  count(*) filter (where status = 'settled' and goals_3plus_hit is true)::bigint as goals_3plus,
  round(100.0 * count(*) filter (where status = 'settled' and goals_3plus_hit is true) / nullif(count(*) filter (where status = 'settled'), 0), 2) as goals_3plus_rate
from public.under3_low_odds_matches
group by trigger_main_ou_line
order by trigger_main_ou_line;

grant select on public.under3_low_odds_stats_by_main_line to anon, authenticated;;
