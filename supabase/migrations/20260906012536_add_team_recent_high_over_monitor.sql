create table if not exists public.team_recent_high_over_matches (
  id bigint generated by default as identity primary key,
  signal_key text not null unique,
  match_key text not null,
  scan_batch_id text not null,
  scan_rule text not null default 'team_last10_over_ge80',
  scanned_at timestamptz not null default now(),
  kickoff_at timestamptz not null,
  competition_name text not null,
  competition_country text,
  competition_level text,
  home_team text not null,
  away_team text not null,
  trend_team text not null,
  trend_team_side text not null check (trend_team_side in ('home','away')),
  recent_sample_size smallint not null default 10 check (recent_sample_size = 10),
  recent_over_count smallint not null check (recent_over_count between 0 and 10),
  recent_push_count smallint not null default 0 check (recent_push_count between 0 and 10),
  recent_under_count smallint not null check (recent_under_count between 0 and 10),
  recent_over_rate numeric(6,2) not null check (recent_over_rate >= 80 and recent_over_rate <= 100),
  over_rate_basis text not null check (over_rate_basis in ('historical_market_main_line','o2.5_score_basis')),
  recent_results jsonb not null default '[]'::jsonb,
  next_ou_line numeric(4,2),
  next_over_odds numeric(6,3),
  next_under_odds numeric(6,3),
  next_line_basis text check (next_line_basis in ('current_market_main_line','o2.5_score_basis')),
  odds_source text,
  history_source text,
  source_match_id text,
  source_url text,
  status text not null default 'scheduled' check (status in ('scheduled','live','finished','settled','postponed','cancelled')),
  home_score smallint,
  away_score smallint,
  total_goals smallint generated always as (
    case when home_score is null or away_score is null then null else home_score + away_score end
  ) stored,
  settlement_line numeric(4,2),
  settlement_result text check (settlement_result in ('OVER','HALF_OVER','PUSH','HALF_UNDER','UNDER')),
  trend_continued boolean generated always as (
    case
      when settlement_result in ('OVER','HALF_OVER') then true
      when settlement_result in ('HALF_UNDER','UNDER') then false
      else null
    end
  ) stored,
  settled_at timestamptz,
  result_source text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint team_recent_high_over_counts_chk check (recent_over_count + recent_push_count + recent_under_count = 10),
  constraint team_recent_high_over_rule_chk check (scan_rule = 'team_last10_over_ge80')
);

create index if not exists team_recent_high_over_kickoff_idx
  on public.team_recent_high_over_matches (kickoff_at);
create index if not exists team_recent_high_over_status_idx
  on public.team_recent_high_over_matches (status);
create index if not exists team_recent_high_over_team_idx
  on public.team_recent_high_over_matches (trend_team);
create index if not exists team_recent_high_over_match_idx
  on public.team_recent_high_over_matches (match_key);

create or replace view public.team_recent_high_over_stats as
select
  count(*)::bigint as total_signals,
  count(distinct match_key)::bigint as unique_matches,
  count(*) filter (where status='settled')::bigint as settled_signals,
  count(*) filter (where settlement_result='OVER')::bigint as full_over,
  count(*) filter (where settlement_result='HALF_OVER')::bigint as half_over,
  count(*) filter (where settlement_result='PUSH')::bigint as push,
  count(*) filter (where settlement_result='HALF_UNDER')::bigint as half_under,
  count(*) filter (where settlement_result='UNDER')::bigint as full_under,
  round(
    100.0 * count(*) filter (where trend_continued is true)
    / nullif(count(*) filter (where status='settled' and settlement_result <> 'PUSH'),0), 2
  ) as simple_continuation_rate,
  round(
    100.0 * (
      count(*) filter (where settlement_result='OVER')
      + 0.5 * count(*) filter (where settlement_result='HALF_OVER')
    )
    / nullif(count(*) filter (where status='settled' and settlement_result <> 'PUSH'),0), 2
  ) as weighted_continuation_rate
from public.team_recent_high_over_matches;

create or replace view public.team_recent_high_over_stats_by_rate as
select
  recent_over_rate,
  count(*)::bigint as total_signals,
  count(*) filter (where status='settled')::bigint as settled_signals,
  count(*) filter (where settlement_result='OVER')::bigint as full_over,
  count(*) filter (where settlement_result='HALF_OVER')::bigint as half_over,
  count(*) filter (where settlement_result='PUSH')::bigint as push,
  count(*) filter (where settlement_result='HALF_UNDER')::bigint as half_under,
  count(*) filter (where settlement_result='UNDER')::bigint as full_under,
  round(
    100.0 * count(*) filter (where trend_continued is true)
    / nullif(count(*) filter (where status='settled' and settlement_result <> 'PUSH'),0), 2
  ) as simple_continuation_rate,
  round(avg(total_goals) filter (where status='settled'),2) as avg_total_goals
from public.team_recent_high_over_matches
group by recent_over_rate
order by recent_over_rate desc;

create or replace view public.team_recent_high_over_dashboard as
select
  id, signal_key, match_key, scan_batch_id, scanned_at, kickoff_at,
  competition_name, competition_country, competition_level,
  home_team, away_team, trend_team, trend_team_side,
  recent_over_count, recent_push_count, recent_under_count, recent_over_rate,
  over_rate_basis, recent_results,
  next_ou_line, next_over_odds, next_under_odds, next_line_basis,
  odds_source, history_source, source_url,
  status, home_score, away_score, total_goals,
  settlement_line, settlement_result, trend_continued,
  settled_at, result_source, updated_at
from public.team_recent_high_over_matches;;
