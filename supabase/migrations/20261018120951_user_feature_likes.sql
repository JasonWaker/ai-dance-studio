create table public.user_feature_likes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  feature_key text not null check (char_length(feature_key) between 3 and 500),
  feature_type text not null check (feature_type in ('system', 'mfdr')),
  label text not null check (char_length(btrim(label)) between 1 and 240),
  feature_snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, feature_key),
  constraint user_feature_likes_snapshot_object check (jsonb_typeof(feature_snapshot) = 'object')
);
create index user_feature_likes_user_updated_idx on public.user_feature_likes (user_id, updated_at desc);
alter table public.user_feature_likes enable row level security;
create policy "feature likes are readable by their owner" on public.user_feature_likes for select to authenticated using ((select auth.uid()) = user_id);
create policy "feature likes are insertable by their owner" on public.user_feature_likes for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "feature likes are updatable by their owner" on public.user_feature_likes for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "feature likes are deletable by their owner" on public.user_feature_likes for delete to authenticated using ((select auth.uid()) = user_id);
grant select, insert, update, delete on public.user_feature_likes to authenticated;
grant usage, select on sequence public.user_feature_likes_id_seq to authenticated;
comment on table public.user_feature_likes is 'Per-user persistent likes for exact system recommendation points and MFDR feature combinations.';;
