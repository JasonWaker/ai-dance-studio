create or replace view public.ah0_away_water_dashboard as
select
  m.*,
  round(extract(epoch from (m.kickoff_at - now())) / 3600.0, 1) as hours_to_kickoff,
  case when m.away_team_zh is not null then m.away_team_zh else m.away_team end as display_away_team,
  case when m.home_team_zh is not null then m.home_team_zh else m.home_team end as display_home_team,
  case when m.competition_name_zh is not null then m.competition_name_zh else m.competition_name end as display_competition_name
from public.ah0_away_water_matches m
where m.away_handicap_odds between 1.80 and 1.88;

create or replace view public.ah0_away_water_stats as
with settled as (
  select * from public.ah0_away_water_matches
  where status = 'settled' and away_result is not null
),
agg as (
  select
    count(*)::int as settled_samples,
    count(*) filter (where away_result='WIN')::int as away_wins,
    count(*) filter (where away_result='PUSH')::int as away_pushes,
    count(*) filter (where away_result='LOSS')::int as away_losses
  from settled
)
select
  settled_samples,
  away_wins,
  away_pushes,
  away_losses,
  case when (away_wins + away_losses) > 0 then round(away_wins::numeric * 100 / (away_wins + away_losses), 2) else null end as away_cover_rate,
  case when settled_samples > 0 then round(away_wins::numeric * 100 / settled_samples, 2) else null end as away_win_rate_including_push
from agg;

create or replace view public.ah0_away_water_stats_by_odds as
select
  round(away_handicap_odds, 2) as away_odds,
  count(*) filter (where status='settled')::int as settled_samples,
  count(*) filter (where status='settled' and away_result='WIN')::int as away_wins,
  count(*) filter (where status='settled' and away_result='PUSH')::int as away_pushes,
  count(*) filter (where status='settled' and away_result='LOSS')::int as away_losses,
  case when count(*) filter (where status='settled' and away_result in ('WIN','LOSS')) > 0
    then round((count(*) filter (where status='settled' and away_result='WIN'))::numeric * 100 /
      count(*) filter (where status='settled' and away_result in ('WIN','LOSS')), 2)
    else null end as away_cover_rate
from public.ah0_away_water_matches
where away_handicap_odds between 1.80 and 1.88
group by round(away_handicap_odds, 2)
order by away_odds;

create or replace function public.ah0_away_water_upsert(p_payload jsonb)
returns public.ah0_away_water_matches
language plpgsql
security invoker
as $$
declare r public.ah0_away_water_matches;
begin
  if coalesce((p_payload->>'handicap_line')::numeric,0) <> 0 then raise exception '盘口必须为客队让0'; end if;
  if (p_payload->>'away_handicap_odds') is null or (p_payload->>'away_handicap_odds')::numeric not between 1.80 and 1.88 then raise exception '客队水位必须在1.80至1.88'; end if;
  insert into public.ah0_away_water_matches(
    match_key,scan_batch_id,kickoff_at,competition_name,competition_country,competition_level,
    home_team,away_team,home_team_zh,away_team_zh,competition_name_zh,source_match_id,
    handicap_line,home_handicap_odds,away_handicap_odds,odds_source,source_url,odds_updated_at,status
  ) values (
    p_payload->>'match_key',p_payload->>'scan_batch_id',(p_payload->>'kickoff_at')::timestamptz,p_payload->>'competition_name',
    p_payload->>'competition_country',p_payload->>'competition_level',p_payload->>'home_team',p_payload->>'away_team',
    p_payload->>'home_team_zh',p_payload->>'away_team_zh',p_payload->>'competition_name_zh',p_payload->>'source_match_id',
    0,(p_payload->>'home_handicap_odds')::numeric,(p_payload->>'away_handicap_odds')::numeric,p_payload->>'odds_source',
    p_payload->>'source_url',(p_payload->>'odds_updated_at')::timestamptz,coalesce(p_payload->>'status','scheduled')
  )
  on conflict(match_key) do update set
    scan_batch_id=excluded.scan_batch_id,
    last_seen_at=now(),
    kickoff_at=excluded.kickoff_at,
    competition_name=excluded.competition_name,
    competition_country=excluded.competition_country,
    competition_level=excluded.competition_level,
    home_team=excluded.home_team,
    away_team=excluded.away_team,
    home_team_zh=coalesce(excluded.home_team_zh, ah0_away_water_matches.home_team_zh),
    away_team_zh=coalesce(excluded.away_team_zh, ah0_away_water_matches.away_team_zh),
    competition_name_zh=coalesce(excluded.competition_name_zh, ah0_away_water_matches.competition_name_zh),
    source_match_id=excluded.source_match_id,
    home_handicap_odds=excluded.home_handicap_odds,
    away_handicap_odds=excluded.away_handicap_odds,
    odds_source=excluded.odds_source,
    source_url=excluded.source_url,
    odds_updated_at=excluded.odds_updated_at,
    status=excluded.status,
    updated_at=now()
  returning * into r;
  insert into public.ah0_away_water_snapshots(match_id,handicap_line,home_handicap_odds,away_handicap_odds,odds_source,source_url,source_match_id)
  values(r.id,0,r.home_handicap_odds,r.away_handicap_odds,r.odds_source,r.source_url,r.source_match_id);
  return r;
end;
$$;

revoke all on function public.ah0_away_water_upsert(jsonb) from anon, authenticated;
grant execute on function public.ah0_away_water_upsert(jsonb) to service_role;
;
