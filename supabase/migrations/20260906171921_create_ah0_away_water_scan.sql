create table if not exists public.ah0_away_water_matches (
  id bigint generated by default as identity primary key,
  match_key text not null unique,
  scan_batch_id text,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  kickoff_at timestamptz not null,
  competition_name text not null,
  competition_country text,
  competition_level text,
  home_team text not null,
  away_team text not null,
  home_team_zh text,
  away_team_zh text,
  competition_name_zh text,
  source_match_id text,
  handicap_line numeric not null default 0 check (handicap_line = 0),
  home_handicap_odds numeric,
  away_handicap_odds numeric not null check (away_handicap_odds >= 1),
  odds_source text,
  source_url text,
  odds_updated_at timestamptz,
  status text not null default 'scheduled' check (status in ('scheduled','live','finished','settled','cancelled','postponed')),
  home_score smallint check (home_score is null or home_score >= 0),
  away_score smallint check (away_score is null or away_score >= 0),
  away_result text check (away_result is null or away_result in ('WIN','PUSH','LOSS')),
  away_cover_rate numeric check (away_cover_rate is null or (away_cover_rate >= 0 and away_cover_rate <= 100)),
  result_source text,
  settled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

